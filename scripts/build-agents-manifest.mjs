// Build step: read .claude/agents/*.md frontmatter.
//  - public/console/agents.json  -> PUBLIC list: name, description, model, personality ONLY (no prompts).
//  - netlify/lib/agents.generated.mjs -> server-only module bundled into Functions: adds effort + prompt body.
// Both outputs are generated (gitignored). No secrets are involved.
import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const dir = join(root, '.claude/agents');

/** Minimal YAML-frontmatter reader for our flat `key: value` fields (lists are skipped). */
export function parseAgent(text) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/.exec(text);
  if (!m) throw new Error('missing frontmatter');
  const fm = {};
  for (const line of m[1].split(/\r?\n/)) {
    const kv = /^([A-Za-z][\w-]*):\s*(.*)$/.exec(line);
    if (kv && kv[2] !== '') fm[kv[1]] = kv[2].replace(/^["']|["']$/g, '').trim();
  }
  return { fm, body: m[2].trim() };
}

const NAME = /^[a-z0-9][a-z0-9-]{0,63}$/;
const agents = [];
for (const file of (await readdir(dir)).filter((f) => f.endsWith('.md')).sort()) {
  const { fm, body } = parseAgent(await readFile(join(dir, file), 'utf8'));
  if (!NAME.test(fm.name ?? '')) throw new Error(`${file}: invalid name`);
  agents.push({ name: fm.name, description: fm.description ?? '', model: fm.model ?? 'inherit', effort: fm.effort ?? null, personality: fm.personality ?? '', prompt: body });
}

await mkdir(join(root, 'public/console'), { recursive: true });
const publicList = agents.map(({ name, description, model, personality }) => ({ name, description, model, personality }));
await writeFile(join(root, 'public/console/agents.json'), JSON.stringify({ agents: publicList }, null, 2) + '\n');
await writeFile(join(root, 'netlify/lib/agents.generated.mjs'),
  '// GENERATED by scripts/build-agents-manifest.mjs - do not edit. Server-only (Functions bundle).\n' +
  `export const AGENTS = ${JSON.stringify(agents, null, 2)};\n`);
console.log(`agents manifest: ${agents.length} agents`);
